import { build } from "esbuild";
import {
  mkdir,
  copyFile,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import { createHash, generateKeyPairSync } from "node:crypto";
const root = new URL("../", import.meta.url);
const path = (s) => new URL(s, root);
const { version } = JSON.parse(await readFile(path("package.json"), "utf8"));
await mkdir(path("extension/dist"), { recursive: true });
// Each build writes its own hashed worker. Drop stale copies so old service
// worker code never ships or gets reloaded after an unpacked upgrade.
for (const f of await readdir(path("extension/dist")))
  if (/^background-.+\.js(\.map)?$/.test(f))
    await rm(path("extension/dist/" + f), { force: true });
let publicKey;
try {
  publicKey = (await readFile(path("extension/public-key.txt"), "utf8")).trim();
} catch {
  const { publicKey: key } = generateKeyPairSync("rsa", {
    modulusLength: 2048,
  });
  publicKey = key.export({ type: "spki", format: "der" }).toString("base64");
  await writeFile(path("extension/public-key.txt"), publicKey + "\n");
}
const id = [
  ...createHash("sha256")
    .update(Buffer.from(publicKey, "base64"))
    .digest()
    .subarray(0, 16),
]
  .map((b) => String.fromCharCode(97 + (b >> 4), 97 + (b & 15)))
  .join("");
const manifest = {
  manifest_version: 3,
  name: "Chrome 操作助手",
  version,
  description: "通过本机连接协助 Codex 读取网页、操作已授权表单和批量采集。",
  minimum_chrome_version: "125",
  key: publicKey,
  permissions: [
    "nativeMessaging",
    "storage",
    "tabs",
    "tabGroups",
    "scripting",
    "webNavigation",
    "webRequest",
    "debugger",
    "downloads",
    "alarms",
  ],
  host_permissions: ["http://*/*", "https://*/*"],
  // Expose manifest.json to the official install guide page so it can detect
  // whether the extension is already loaded (fetch chrome-extension://<id>/manifest.json).
  web_accessible_resources: [
    {
      resources: ["manifest.json"],
      matches: ["https://install.bingbing.asia/*"],
    },
  ],
  background: { service_worker: "background.js", type: "module" },
  action: { default_popup: "ui.html", default_title: "Chrome 操作助手" },
  options_page: "ui.html",
};
await writeFile(
  path("internal/app/identity.go"),
  `// Code generated by scripts/build-extension.mjs. Preserve extension/public-key.txt across releases.\npackage app\nconst ExtensionID = "${id}"\n`,
);
await build({
  entryPoints: ["background", "content", "ui", "window"].map((x) =>
    new URL(`extension/src/${x}.ts`, root).pathname.replace(
      /^\/([A-Za-z]:)/,
      "$1",
    ),
  ),
  outdir: new URL("extension/dist/", root).pathname.replace(
    /^\/([A-Za-z]:)/,
    "$1",
  ),
  bundle: true,
  format: "iife",
  target: "chrome125",
  sourcemap: true,
});
for (const name of ["ui.html", "ui.css", "window.html", "window.css"])
  await copyFile(path("extension/" + name), path("extension/dist/" + name));
// Unpacked-extension upgrades must not reuse a cached service-worker entry.
// Publish the manifest last so it only references a fully written worker.
const workerHash = createHash("sha256")
  .update(await readFile(path("extension/dist/background.js")))
  .digest("hex").slice(0, 16);
const workerName = `background-${version}-${workerHash}.js`;
await copyFile(path("extension/dist/background.js"), path(`extension/dist/${workerName}`));
manifest.background.service_worker = workerName;
await writeFile(
  path("extension/dist/manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n",
);
console.log(JSON.stringify({ extensionId: id, version: manifest.version }));
